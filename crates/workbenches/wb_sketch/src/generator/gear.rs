        let outline = spec.outline().unwrap();
        let (lo, hi) = outline_radii(&outline);
        assert!((hi - g.tip_radius).abs() < 1e-6, "{hi}");
        assert!((lo - g.root_radius).abs() < 1e-6, "{lo}");
        let lp = &outline.loops[0];
