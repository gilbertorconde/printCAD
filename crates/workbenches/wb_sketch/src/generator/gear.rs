    /// A pinion of few teeth, generated by a rack cutter, is undercut: the
    /// cutter's rounded tip cuts into the involute above the base circle.
    /// A gear of many teeth is not.
    #[test]
    fn a_pinion_of_few_teeth_is_undercut_and_a_large_gear_is_not() {
        for (teeth, undercut) in [(8, true), (12, true), (40, false)] {
            let gear = GearSpec {
                teeth,
                ..GearSpec::default()
            };
            let g = gear.geometry().unwrap();
            let flank = generated_flank(&g, 0.38 * 2.0).unwrap();
            let inside = flank.trochoid.iter().any(|p| {
                let r = norm(*p);
                r >= g.base_radius && p[1].atan2(p[0]) < g.half_angle(r) - 1e-6
            });
            assert_eq!(inside, undercut, "{teeth} teeth");
            assert_eq!(gear.is_undercut(), undercut, "{teeth} teeth");
            assert!(flank.junction > g.base_radius && flank.junction < g.tip_radius);
        }
    }

    /// How far the gear's point `p` (gap frame) lies inside the cutter's
    /// tooth at roll `phi`; negative outside.
    fn depth_in(g: &GearGeometry, rack: &Rack, p: P2, phi: f64) -> f64 {
        let r = g.pitch_radius;
        let half_width = r * (PI / f64::from(g.teeth) - g.half_thickness);
        let w = rotate(p, phi);
        let (x, y) = (w[0], (w[1] - r * phi).abs());
        let (s, c) = g.pressure_angle.sin_cos();
        // Inside the tip line (the root circle), and inside the slanted
        // flank.
        let below_tip = x - g.root_radius;
        let flank = (half_width + (x - r) * g.pressure_angle.tan() - y) * c;
        let mut depth = below_tip.min(flank);
        // Past the rounding's centre on both sides, the rounding bounds it.
        let [cx, cy] = rack.corner;
        if x < cx - rack.rho * s && y > cy {
            depth = depth.min(rack.rho - norm(sub([x, y], rack.corner)));
        }
        depth
    }

    /// The rack cutter rolls past the teeth it generates without cutting
    /// into them: at every roll, no point of the drawn outline lies inside
    /// the cutter's tooth by more than the flank's tolerance.
    #[test]
    fn the_cutter_rolls_past_the_generated_teeth_without_cutting_them() {
        for teeth in [8, 14, 30] {
            let gear = GearSpec {
                teeth,
                bore: 0.0,
                ..GearSpec::default()
            };
            let g = gear.geometry().unwrap();
            let rack = Rack::of(&g, 0.38 * 2.0).unwrap();
            let half_pitch = PI / f64::from(teeth);
            // The outline seen from the space between teeth 0 and 1.
            let points: Vec<P2> = gear.outline().unwrap().loops[0]
                .polyline(64)
                .into_iter()
                .map(|p| rotate(p, -half_pitch))
                .collect();
            let mut deepest = f64::MIN;
            for i in 0..=400 {
                let phi = -2.0 * half_pitch + 4.0 * half_pitch * f64::from(i) / 400.0;
                for p in &points {
                    deepest = deepest.max(depth_in(&g, &rack, *p, phi));
                }
            }
            assert!(deepest < 2.0 * FLANK_TOLERANCE, "{teeth} teeth: {deepest}");
            // And it touches them: the root circle is cut.
            assert!(deepest > -FLANK_TOLERANCE, "{teeth} teeth: {deepest}");
        }
    }

