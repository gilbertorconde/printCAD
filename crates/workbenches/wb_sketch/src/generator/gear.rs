//! An involute spur gear: module, teeth and pressure angle, with a
//! profile shift, addendum and dedendum, backlash, a root fillet and a
//! bore; or an internal (ring) gear, its teeth pointing in from a rim.
//!
//! A ring's tooth spaces have the shape of an outer gear's teeth, so its
//! inner outline is drawn as that of an outer gear whose teeth are the
//! spaces: from the ring's tip circle up to its root circle. Its roots
//! are left sharp.
//!
//! Each flank is the involute of the base circle from where the root
//! fillet meets it to the tip circle, as a B-spline within
//! [`FLANK_TOLERANCE`] of the true curve; below the base circle, where no
//! involute exists, the flank runs radially down to the fillet. The tip
//! and root are arcs of their circles.
//!
//! With `undercut` the root is the one a rack cutter leaves (the gear
//! generated by a rack whose tip is rounded by the root fillet): the
//! trochoid the rounded tip traces runs from the root circle up to where
//! the involute takes over, and on a pinion of few teeth it cuts into the
//! involute above the base circle, as the cutter does.

use serde::{Deserialize, Serialize};
use std::f64::consts::PI;

use super::keyway::BoreKeyway;
use super::{Edge, Loop, Outline, P2, add, fit, norm, polar, rotate, scale, sub};

/// How far a flank's spline may stray from the involute, mm.
pub const FLANK_TOLERANCE: f64 = 0.001;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, from = "StoredGear")]
pub struct GearSpec {
    /// Pitch diameter over teeth, mm.
    pub module: f64,
    #[serde(deserialize_with = "super::count")]
    pub teeth: u32,
    pub pressure_angle_deg: f64,
    /// Profile shift coefficient: the tooth moved out, away from the
    /// gear's centre, by this many modules.
    pub profile_shift: f64,
    /// Addendum coefficient: the tip stands this many modules beyond the
    /// pitch circle.
    pub addendum: f64,
    /// Dedendum coefficient: the root sits this many modules inside the
    /// pitch circle (outside it, on a ring).
    pub dedendum: f64,
    /// How much thinner each tooth is than half the circular pitch at the
    /// pitch circle, mm.
    pub backlash: f64,
    /// Root fillet radius coefficient, in modules; 0 leaves a sharp root.
    pub root_fillet: f64,
    /// Bore diameter, mm; 0 leaves the gear solid. Not used by a ring.
    pub bore: f64,
    /// An internal (ring) gear.
    pub internal: bool,
    /// A ring's outside diameter, mm; 0 makes it three modules beyond the
    /// root circle.
    pub rim: f64,
    /// The root as a rack cutter leaves it, undercutting the flanks of a
    /// pinion of few teeth; off, a root fillet arc. Not used by a ring.
    pub undercut: bool,
    /// A keyway in the bore. Not used by a ring.
    pub keyway: BoreKeyway,
}

/// A gear as files hold it: one with no dedendum gives its root as a
/// clearance past the mating tip.
#[derive(Deserialize)]
#[serde(default)]
struct StoredGear {
    module: f64,
    #[serde(deserialize_with = "super::count")]
    teeth: u32,
    pressure_angle_deg: f64,
    profile_shift: f64,
    addendum: Option<f64>,
    dedendum: Option<f64>,
    clearance: Option<f64>,
    backlash: f64,
    root_fillet: f64,
    bore: f64,
    internal: bool,
    rim: f64,
    /// Absent from gears saved before the cutter's root, which keep the
    /// root fillet arc.
    undercut: bool,
    keyway: BoreKeyway,
}

impl Default for StoredGear {
    fn default() -> Self {
        let d = GearSpec::default();
        Self {
            module: d.module,
            teeth: d.teeth,
            pressure_angle_deg: d.pressure_angle_deg,
            profile_shift: d.profile_shift,
            addendum: None,
            dedendum: None,
            clearance: None,
            backlash: d.backlash,
            root_fillet: d.root_fillet,
            bore: d.bore,
            internal: d.internal,
            rim: d.rim,
            undercut: false,
            keyway: d.keyway,
        }
    }
}

impl From<StoredGear> for GearSpec {
    fn from(s: StoredGear) -> Self {
        let addendum = s.addendum.unwrap_or(1.0);
        Self {
            module: s.module,
            teeth: s.teeth,
            pressure_angle_deg: s.pressure_angle_deg,
            profile_shift: s.profile_shift,
            addendum,
            dedendum: s
                .dedendum
                .unwrap_or_else(|| addendum + s.clearance.unwrap_or(0.25)),
            backlash: s.backlash,
            root_fillet: s.root_fillet,
            bore: s.bore,
            internal: s.internal,
            rim: s.rim,
            undercut: s.undercut,
            keyway: s.keyway,
        }
    }
}

