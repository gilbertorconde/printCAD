/// tan φ − φ.
pub fn involute_function(phi: f64) -> f64 {
    phi.tan() - phi
}

/// The measured circles and angles of a gear, in millimetres and radians.
/// For a ring these describe its tooth spaces as an outer gear's teeth:
/// `tip_radius` is the ring's root circle and `root_radius` its tip
/// circle.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GearGeometry {
    pub pitch_radius: f64,
    pub base_radius: f64,
    pub tip_radius: f64,
    pub root_radius: f64,
    /// Half the tooth's angular thickness at the pitch circle.
    pub half_thickness: f64,
    pub pressure_angle: f64,
    pub teeth: u32,
}

impl GearGeometry {
    /// Half the tooth's angular thickness at radius `r` on the involute
    /// (`r` at least the base radius); below it, where the flank runs
    /// radially, the angle at the base circle.
    pub fn half_angle(&self, r: f64) -> f64 {
        let r = r.max(self.base_radius);
        let phi = (self.base_radius / r).clamp(-1.0, 1.0).acos();
        self.half_thickness + involute_function(self.pressure_angle) - involute_function(phi)
    }

    /// The left flank of the tooth centred on angle 0 at radius `r`.
    pub fn flank_point(&self, r: f64) -> P2 {
        polar(r, self.half_angle(r))
    }

    /// The flank's unit normal at radius `r`, pointing out of the tooth.
    fn flank_normal(&self, r: f64) -> P2 {
        let a = self.half_angle(r);
        let radial = polar(1.0, a);
        let across = polar(1.0, a + PI / 2.0);
        // The involute leans back by its pressure angle there: tan φ of
        // radial for one of across.
        let t = if r > self.base_radius {
            (r * r - self.base_radius * self.base_radius).sqrt() / self.base_radius
        } else {
            0.0
        };
        let n = add(scale(radial, t), across);
        scale(n, 1.0 / norm(n))
    }
}

impl GearSpec {
    pub fn geometry(&self) -> Result<GearGeometry, String> {
        let m = self.module;
        if !(m > 0.0 && m.is_finite()) {
            return Err("the module must be more than zero".into());
        }
        if self.teeth < 3 {
            return Err("a gear needs at least 3 teeth".into());
        }
        let alpha = self.pressure_angle_deg.to_radians();
        if !(alpha > 0.0 && alpha < 45f64.to_radians()) {
            return Err("the pressure angle must be between 0° and 45°".into());
        }
        let (ha, hf) = (self.addendum, self.dedendum);
        if !(ha >= 0.0 && hf > 0.0 && ha.is_finite() && hf.is_finite()) {
            return Err("the addendum and dedendum must be more than zero".into());
        }
        let z = f64::from(self.teeth);
        let x = self.profile_shift;
        let r = m * z / 2.0;
        let shifted = m * (PI / 2.0 + 2.0 * x * alpha.tan());
        let backlash = self.backlash;
        // A ring's space, drawn as a tooth, reaches out to its root circle
        // and in to its tip circle; backlash widens it.
        let (s, tip, root) = if self.internal {
            (shifted + backlash, r + m * (hf + x), r - m * (ha - x))
        } else {
            (shifted - backlash, r + m * (ha + x), r - m * (hf - x))
        };
        let g = GearGeometry {
            pitch_radius: r,
            base_radius: r * alpha.cos(),
            tip_radius: tip,
            root_radius: root,
            half_thickness: s / (2.0 * r),
            pressure_angle: alpha,
            teeth: self.teeth,
        };
        if g.root_radius <= 0.0 {
            return Err(if self.internal {
                "the tip circle comes to nothing: use more teeth or a smaller addendum".into()
            } else {
                "the root circle comes to nothing: use more teeth or a smaller dedendum".into()
            });
        }
        if g.root_radius >= g.tip_radius {
            return Err("the root circle is outside the tip circle".into());
        }
        if g.half_angle(g.tip_radius) <= 0.0 {
            return Err(
                "the teeth come to a point below the tip circle: use less profile shift or \
                 backlash"
                    .into(),
            );
        }
        if g.half_angle(g.root_radius) >= PI / z {
            return Err("the teeth meet at the root: use a larger backlash or fewer teeth".into());
        }
        if self.internal {
            if self.rim_radius(&g) <= g.tip_radius {
                return Err("the rim must be outside the root circle".into());
            }
            return Ok(g);
        }
        let bore = self.bore;
        if bore < 0.0 || bore / 2.0 >= g.root_radius {
            return Err("the bore must fit inside the root circle".into());
        }
        if self.keyway.on && bore <= 0.0 {
            return Err("a keyway needs a bore".into());
        }
        Ok(g)
    }

    /// A ring's outside radius.
    fn rim_radius(&self, g: &GearGeometry) -> f64 {
        if self.rim > 0.0 {
            self.rim / 2.0
        } else {
            g.tip_radius + 3.0 * self.module
        }
    }

    /// Whether the teeth are undercut at their root, as a rack cutter
    /// leaves a pinion of few teeth.
    pub fn is_undercut(&self) -> bool {
        let rho = self.root_fillet.max(0.0) * self.module;
        self.geometry()
            .and_then(|g| generated_flank(&g, rho))
            .is_ok_and(|f| f.undercut)
    }

    /// The tip and root diameters of the gear as made: a ring's tip circle
    /// is inside its root circle.
    pub fn tip_and_root_diameters(&self) -> Result<(f64, f64), String> {
        let g = self.geometry()?;
        let (tip, root) = if self.internal {
            (g.root_radius, g.tip_radius)
        } else {
            (g.tip_radius, g.root_radius)
        };
        Ok((2.0 * tip, 2.0 * root))
    }

    pub fn outline(&self) -> Result<Outline, String> {
        let g = self.geometry()?;
        let z = self.teeth as usize;
        let pitch = 2.0 * PI / z as f64;
        let rho = if self.internal {
            0.0
        } else {
            self.root_fillet.max(0.0) * self.module
        };
        if self.undercut && !self.internal {
            let lp = generated_loop(&g, rho)?;
            return self.finished(&g, lp);
        }
        let foot = root_foot(&g, rho);

        // The left flank of tooth 0, bottom to top: the fillet's end on
        // the flank, a radial line to the base circle when it is below
        // it, then the involute to the tip.
        let start = foot.flank_radius;
        let involute_from = start.max(g.base_radius);
        let radial = (start < g.base_radius - 1e-9).then(|| g.flank_point(g.base_radius));
        let spline = involute_spline(&g, involute_from, g.tip_radius);

        let mirror = |p: P2| [p[0], -p[1]];
        let tip = *spline.last().expect("poles");
        let inner = &spline[1..spline.len() - 1];
        let root_arc = || Edge::Arc { center: [0.0, 0.0] };
        let mut lp = Loop::default();
        for k in 0..z {
            let turn = pitch * k as f64;
            let right = |p: P2| rotate(mirror(p), turn);
            let left = |p: P2| rotate(p, turn);
            // Each joint with the edge that leaves it: up the right flank
            // from the root, over the tip, down the left flank, and along
            // the root to the next tooth.
            let mut chain: Vec<(P2, Edge)> = Vec::new();
            if let Some(f) = &foot.fillet {
                chain.push((
                    right(f.on_root),
                    Edge::Arc {
                        center: right(f.center),
                    },
                ));
            }
            let right_inner = Edge::Spline {
                inner: inner.iter().map(|p| right(*p)).collect(),
            };
            match radial {
                Some(base) => {
                    chain.push((right(g.flank_point(start)), Edge::Line));
                    chain.push((right(base), right_inner));
                }
                None => chain.push((right(spline[0]), right_inner)),
            }
            chain.push((right(tip), root_arc()));
            chain.push((
                left(tip),
                Edge::Spline {
                    inner: inner.iter().rev().map(|p| left(*p)).collect(),
                },
            ));
            let down = match &foot.fillet {
                Some(f) => Edge::Arc {
                    center: left(f.center),
                },
                None => root_arc(),
            };
            match radial {
                Some(base) => {
                    chain.push((left(base), Edge::Line));
                    chain.push((left(g.flank_point(start)), down));
                }
                None => chain.push((left(spline[0]), down)),
            }
            if let Some(f) = &foot.fillet {
                chain.push((left(f.on_root), root_arc()));
            }
            for (joint, edge) in chain {
                lp.joints.push(joint);
                lp.edges.push(edge);
            }
        }

        self.finished(&g, lp)
    }

    /// The outline of the teeth `lp` with the pitch circle, and the rim, or
    /// the bore and its keyway.
    fn finished(&self, g: &GearGeometry, lp: Loop) -> Result<Outline, String> {
        let mut outline = Outline {
            loops: vec![lp],
            guides: vec![([0.0, 0.0], g.pitch_radius)],
            ..Outline::default()
        };
        let bore = self.bore;
        if self.internal {
            outline.circles.push(([0.0, 0.0], self.rim_radius(g)));
        } else if self.keyway.on {
            outline
                .holes
                .push(self.keyway.bore_loop(bore, g.root_radius)?);
        } else if bore > 0.0 {
            outline.circles.push(([0.0, 0.0], bore / 2.0));
        }
        Ok(outline)
    }
}

/// The teeth as a rack cutter whose tip is rounded `rho` generates them:
/// up each flank the trochoid then the involute, over the tip and along
/// the root to the next tooth.
fn generated_loop(g: &GearGeometry, rho: f64) -> Result<Loop, String> {
    let flank = generated_flank(g, rho)?;
    let pitch = 2.0 * PI / f64::from(g.teeth);
    let involute = involute_spline(g, flank.junction, g.tip_radius);
    let line = &flank.trochoid;
    let trochoid = fit::fit(line, FLANK_TOLERANCE, 40, |p| off_polyline(line, p)).0;
    let foot = trochoid[0];
    let junction = *trochoid.last().expect("poles");
    let tip = *involute.last().expect("poles");
    let inner = |poles: &[P2]| poles[1..poles.len() - 1].to_vec();
    let (troch_inner, inv_inner) = (inner(&trochoid), inner(&involute));
    let mirror = |p: P2| [p[0], -p[1]];
    let mut lp = Loop::default();
    for k in 0..g.teeth {
        let turn = pitch * f64::from(k);
        let right = |p: P2| rotate(mirror(p), turn);
        let left = |p: P2| rotate(p, turn);
        let spline = |poles: &[P2], at: &dyn Fn(P2) -> P2, rev: bool| {
            let mut inner: Vec<P2> = poles.iter().map(|p| at(*p)).collect();
            if rev {
                inner.reverse();
            }
            Edge::Spline { inner }
        };
        let root_arc = || Edge::Arc { center: [0.0, 0.0] };
        let chain = [
            (right(foot), spline(&troch_inner, &right, false)),
            (right(junction), spline(&inv_inner, &right, false)),
            (right(tip), root_arc()),
            (left(tip), spline(&inv_inner, &left, true)),
            (left(junction), spline(&troch_inner, &left, true)),
            (left(foot), root_arc()),
        ];
        for (joint, edge) in chain {
            lp.joints.push(joint);
            lp.edges.push(edge);
        }
    }
    Ok(lp)
}

/// The left flank of tooth 0 as a rack cutter generates it, from the root
/// circle up to the tip: the trochoid its rounded tip traces, then the
/// involute its straight flank leaves. On a pinion of few teeth the
/// trochoid cuts into the involute above the base circle (undercut).
pub(crate) struct GeneratedFlank {
    /// The trochoid from the root circle to where the involute takes
    /// over, densely sampled.
    pub trochoid: Vec<P2>,
    /// The radius the involute takes over at.
    pub junction: f64,
    /// Whether the trochoid cuts into the involute.
    pub undercut: bool,
}

/// The rack cutter that generates `g`'s teeth, its tip rounded `rho`:
/// in the rack's own frame, X out from the gear's centre and Y along the
/// rack, the rolling line at X = the pitch radius.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Rack {
    pitch_radius: f64,
    pressure_angle: f64,
    rho: f64,
    /// The centre of the rounding at the tip's +Y corner.
    corner: P2,
}

impl Rack {
    pub(crate) fn of(g: &GearGeometry, rho: f64) -> Result<Self, String> {
        let r = g.pitch_radius;
        let alpha = g.pressure_angle;
        let half_width = r * (PI / f64::from(g.teeth) - g.half_thickness);
        let tip = g.root_radius;
        let at_tip = half_width + (tip - r) * alpha.tan();
        if at_tip <= 0.0 {
            return Err(
                "the cutter's tip comes to a point: use less dedendum or profile shift".into(),
            );
        }
        // The roundings of the two corners keep apart.
        let widest = at_tip / (1.0 / alpha.cos() - alpha.tan());
        let rho = rho.clamp(0.0, 0.95 * widest);
        let x = tip + rho;
        let corner = [x, half_width + (x - r) * alpha.tan() - rho / alpha.cos()];
        if corner[0] >= r {
            return Err("the cutter's tip reaches past the pitch circle".into());
        }
        Ok(Self {
            pitch_radius: r,
            pressure_angle: alpha,
            rho,
            corner,
        })
    }

    /// The roll angles over which the +Y corner's rounding cuts: from
    /// where it cuts the root circle to where the straight flank takes
    /// over.
    fn span(&self) -> (f64, f64) {
        let r = self.pitch_radius;
        let [cx, cy] = self.corner;
        (-cy / r, ((r - cx) / self.pressure_angle.tan() - cy) / r)
    }

    /// The point the corner's rounding cuts at roll `phi`, in the gear's
    /// frame with the tooth space centred on angle 0: where the rounding's
    /// normal runs through the pitch point.
    fn cut_at(&self, phi: f64) -> P2 {
        let r = self.pitch_radius;
        let c = [self.corner[0], self.corner[1] + r * phi];
        let to_pitch = sub([r, 0.0], c);
        let n = norm(to_pitch);
        let q = if n > 1e-12 {
            sub(c, scale(to_pitch, self.rho / n))
        } else {
            c
        };
        rotate(q, -phi)
    }
}

/// `p` (gap frame, on the +Y side) on tooth 0's left flank.
fn gap_to_tooth(p: P2, teeth: u32) -> P2 {
    let angle = PI / f64::from(teeth) - p[1].atan2(p[0]);
    polar(norm(p), angle)
}

/// The flank as a cutter whose tip is rounded `rho` generates it.
pub(crate) fn generated_flank(g: &GearGeometry, rho: f64) -> Result<GeneratedFlank, String> {
    let rack = Rack::of(g, rho)?;
    let (phi0, phi1) = rack.span();
    let at = |phi: f64| gap_to_tooth(rack.cut_at(phi), g.teeth);
    // How far the cut lies outside the involute, in angle: negative where
    // it cuts into it.
    let outside = |p: P2| {
        let r = norm(p);
        (r >= g.base_radius).then(|| p[1].atan2(p[0]) - g.half_angle(r))
    };
    const SAMPLES: usize = 600;
    let phis: Vec<f64> = (0..=SAMPLES)
        .map(|i| phi0 + (phi1 - phi0) * i as f64 / SAMPLES as f64)
        .collect();
    let first_in = phis
        .iter()
        .position(|phi| outside(at(*phi)).is_some_and(|d| d < -1e-9));
    let end = match first_in {
        None => phi1,
        Some(i) => {
            match (i..phis.len()).find(|&j| outside(at(phis[j])).is_some_and(|d| d >= 0.0)) {
                None => phi1,
                Some(j) => {
                    let (mut lo, mut hi) = (phis[j - 1], phis[j]);
                    for _ in 0..60 {
                        let mid = 0.5 * (lo + hi);
                        if outside(at(mid)).is_some_and(|d| d >= 0.0) {
                            hi = mid;
                        } else {
                            lo = mid;
                        }
                    }
                    hi
                }
            }
        }
    };
    let trochoid: Vec<P2> = (0..=SAMPLES)
        .map(|i| at(phi0 + (end - phi0) * i as f64 / SAMPLES as f64))
        .collect();
    let junction = norm(*trochoid.last().expect("samples"));
    if junction >= g.tip_radius {
        return Err("the cutter undercuts the whole flank: use more teeth or profile shift".into());
    }
    Ok(GeneratedFlank {
        trochoid,
        junction,
        undercut: first_in.is_some(),
    })
}

/// How far `p` is from the polyline `line`.
fn off_polyline(line: &[P2], p: P2) -> f64 {
    line.windows(2)
        .map(|w| {
            let d = sub(w[1], w[0]);
            let len2 = d[0] * d[0] + d[1] * d[1];
            let t = if len2 > 0.0 {
                ((p[0] - w[0][0]) * d[0] + (p[1] - w[0][1]) * d[1]) / len2
            } else {
                0.0
            };
            norm(sub(p, add(w[0], scale(d, t.clamp(0.0, 1.0)))))
        })
        .fold(f64::MAX, f64::min)
}

/// Where the root fillet of the tooth centred on angle 0 sits, on its left
/// flank.
#[derive(Debug, Clone, Copy)]
struct Fillet {
    center: P2,
    /// Where it meets the root circle.
    on_root: P2,
}

struct Foot {
    /// Where the flank begins, as a radius: the fillet's end on it, or the
    /// root circle when there is no fillet.
    flank_radius: f64,
    fillet: Option<Fillet>,
}

/// The root fillet of radius `rho`, tangent to the root circle and the
/// flank; smaller when the gap between teeth is too narrow for it, none
/// when it cannot be made at all.
fn root_foot(g: &GearGeometry, rho: f64) -> Foot {
    let half_gap = PI / f64::from(g.teeth);
    let bare = Foot {
        flank_radius: g.root_radius,
        fillet: None,
    };
    let mut rho = rho;
    for _ in 0..24 {
        if rho < 1e-4 {
            return bare;
        }
        if let Some((r, center)) = fillet_on_flank(g, rho) {
            let angle = center[1].atan2(center[0]);
            // The fillets of both flanks leave some root arc between them.
            if angle < half_gap * 0.98 {
                return Foot {
                    flank_radius: r,
                    fillet: Some(Fillet {
                        center,
                        on_root: polar(g.root_radius, angle),
                    }),
                };
            }
        }
        rho *= 0.7;
    }
    bare
}

/// The radius on the flank where a circle of radius `rho` touches both it
/// and the root circle from the gap's side, and that circle's centre.
fn fillet_on_flank(g: &GearGeometry, rho: f64) -> Option<(f64, P2)> {
    let reach = |r: f64| {
        let c = add(g.flank_point(r), scale(g.flank_normal(r), rho));
        (norm(c) - (g.root_radius + rho), c)
    };
    let (mut lo, mut hi) = (g.root_radius, g.tip_radius);
    if reach(lo).0 >= 0.0 || reach(hi).0 <= 0.0 {
        return None;
    }
    for _ in 0..80 {
        let mid = 0.5 * (lo + hi);
        if reach(mid).0 < 0.0 {
            lo = mid;
        } else {
            hi = mid;
        }
    }
    let r = 0.5 * (lo + hi);
    Some((r, reach(r).1))
}

/// The control points of the left flank's involute of tooth 0 from radius
/// `from` to `to`.
fn involute_spline(g: &GearGeometry, from: f64, to: f64) -> Vec<P2> {
    let rb = g.base_radius;
    // Evenly in the roll angle, which crowds the points near the base
    // circle where the involute bends most.
    let roll = |r: f64| ((r / rb).powi(2) - 1.0).max(0.0).sqrt();
    let (t0, t1) = (roll(from), roll(to));
    let points: Vec<P2> = (0..=240)
        .map(|i| {
            let t = t0 + (t1 - t0) * i as f64 / 240.0;
            g.flank_point(rb * (1.0 + t * t).sqrt())
        })
        .collect();
    // How far a point is from the involute: along the circle through it,
    // which is never less than the distance square to the curve.
    let error = |p: P2| {
        let r = norm(p);
        let angle = p[1].atan2(p[0]);
        if r < rb {
            return (rb - r) + r * (angle - g.half_angle(rb)).abs();
        }
        r * (angle - g.half_angle(r)).abs()
    };
    fit::fit(&points, FLANK_TOLERANCE, 40, error).0
}

